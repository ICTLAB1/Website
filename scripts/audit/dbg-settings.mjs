import { chromium } from "playwright";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await (await b.newContext({ viewport: { width: 1440, height: 1400 } })).newPage();
page.on("pageerror", e => console.log("PAGEERROR:", String(e).slice(0, 200)));
await page.goto("http://localhost:3000/login", { waitUntil: "load" });
await page.getByLabel("Business email").fill("admin@example.test");
await page.getByLabel("Password").fill("ChangeMe!Admin123");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL("**/admin", { timeout: 15000 });
const r = await page.goto("http://localhost:3000/admin/settings", { waitUntil: "load" });
console.log("settings status:", r?.status());
console.log("fields:", await page.locator('main [name="grievanceName"]').count());
await page.locator('main [name="grievanceName"]').fill("Debug Officer");
await page.locator("main").getByRole("button", { name: /Save details/i }).click();
await page.waitForTimeout(1500);
console.log("url after save:", page.url());
console.log("fields after save:", await page.locator('main [name="grievanceName"]').count());
console.log("body snippet:", (await page.locator("body").innerText()).slice(0, 400).replace(/\n+/g, " | "));
await b.close();
